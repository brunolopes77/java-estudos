package JavaBasicoExercicios.ExerciciosComplementares;

public class CalculoDeFatorial {
    public static void main(String[] args) {
        int fatorial1 = 0;
        long resultado1 = 1;
        for (int i = fatorial1; i >= 1 ; i--) {
            resultado1 *= i;
        }
        System.out.println(resultado1);
    }
}